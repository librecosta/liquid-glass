export type Language = "en" | "zh-CN";
export type Translator = (
  key: Key,
  vars?: Record<string, string | number>,
) => string;
export const translate =
  (language: Language): Translator =>
  (key, vars = {}) =>
    (language === "zh-CN" ? zh[key] : en[key]).replace(
      /\{(\w+)\}/g,
      (_, name: string) => String(vars[name] ?? `{${name}}`),
    );
const valid = (value: string | null): value is Language =>
  value === "en" || value === "zh-CN";
const storageKey = "liquid-glass:language";
function initialLanguage(): Language {
  const query = new URLSearchParams(location.search).get("lang");
  if (valid(query)) return query;
  try {
    const saved = localStorage.getItem(storageKey);
    if (valid(saved)) return saved;
  } catch {
    /* storage can be blocked */
  }
  return "en";
}
export function useLanguage(title: "pageTitle" | "examplesTitle") {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  useEffect(() => {
    document.documentElement.lang = language;
    document.title = translate(language)(title);
    try {
      localStorage.setItem(storageKey, language);
    } catch {
      /* URL still shares language */
    }
    const url = new URL(location.href);
    url.searchParams.set("lang", language);
    history.replaceState(null, "", url);
  }, [language, title]);
  return { language, setLanguage, t: translate(language) };
}

